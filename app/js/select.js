const poblarEstilos = () => {
    let estiloSelect = document.getElementById("select-estilo");
    for (let i= 0;i< data.Estilos.length-1; i++) {
        let option = document.createElement("option");
        option.value = data.Estilos[i][0];
        option.text = data.Estilos[i][0];
        estiloSelect.appendChild(option);
    }
    let option = document.createElement("option");
    option.value = "Otro.mod"
    option.text = "Otro"
    estiloSelect.appendChild(option);
};

const poblarColores = () => {
    let colorSelect = document.getElementById("select-color");
    for (let i= 0;i< data.Colores.length; i++) {
          let option = document.createElement("option");
          option.value = data.Colores[i];
          option.text = data.Colores[i];
          colorSelect.appendChild(option);
    }
};

const updateTallas = () => {
    let estiloSelect = document.getElementById("select-estilo");
    let tallasSelect = document.getElementById("select-talla");
    let selectedEstilo = estiloSelect.value;

    document.getElementById("talla1").style.display = "none";
    document.getElementById("talla2").style.display = "none";
	document.getElementById("select-talla").required = false;
	document.getElementById("select-estilo2").required = false;
	document.getElementById("select-talla2").required = false;

    if(selectedEstilo === "") return;

    if(selectedEstilo === "Otro.mod") {
        document.getElementById("talla2").style.display = "block";
		document.getElementById("select-estilo2").required = true;
		document.getElementById("select-talla2").required = true;
    }

    else{
        document.getElementById("talla1").style.display = "block";
        tallasSelect.innerHTML = '<option value="">Seleccione la talla</option>';
		document.getElementById("select-talla").required = true;
        const estiloEncontrado = data.Estilos.find(estilo => estilo[0] === selectedEstilo);

        if (estiloEncontrado) {
            const tallas = estiloEncontrado[1];
            for (let i = tallas[0]; i <= tallas[1]; i++) {
                let option = document.createElement("option");
                option.value = i;
                option.text = i;
                tallasSelect.appendChild(option);
            }
        }
    }
};

function initFormSelects() {
    if (!document.getElementById('select-region')) return;

    poblarRegiones();
    poblarEstilos();
    poblarColores();
    poblarSocial();

    document.getElementById("select-region").addEventListener("change", updateRegiones);
    document.getElementById("select-estilo").addEventListener("change", updateTallas);
    document.getElementById("select-contacto").addEventListener("change", updateSocial);
}

document.addEventListener('navbar:loaded', initFormSelects);

if (document.getElementById('select-region')) initFormSelects();